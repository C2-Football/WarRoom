'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const folder = path.join(root, 'images/time-league/helmets');
const manifest = JSON.parse(fs.readFileSync(path.join(folder, 'manifest.json'), 'utf8'));
const sources = {};
for (const item of manifest) {
    if (!/^[a-z]+\.svg$/.test(item.file)) throw Error('Unexpected helmet source filename');
    const bytes = fs.readFileSync(path.join(folder, item.file));
    if (crypto.createHash('sha256').update(bytes).digest('hex') !== item.sha256) throw Error(item.id + ' differs from the original downloaded asset');
    sources[item.id] = bytes.toString('utf8');
}
const output = '// Generated by scripts/build-time-league-helmet-sources.cjs from complete CC0 originals. Do not hand edit.\n' +
    '(function(root){root.App=root.App||{};root.App.TimeLeagueHelmetSources=Object.freeze(' + JSON.stringify(sources) + ');})(typeof window!=="undefined"?window:globalThis);\n';
const target = path.join(root, 'js/shared/time-league-helmet-sources.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error('Rebuild the complete helmet source bundle');
    console.log('Complete helmet source files and generated bundle match their recorded originals.');
} else {
    fs.writeFileSync(target, output);
    console.log('Bundled ' + manifest.length + ' complete helmet source assets.');
}
