const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const events = [];
let now = 1000;
const window = { dispatchEvent: e => events.push(e), CustomEvent: class { constructor(type, options) { this.type = type; this.detail = options.detail; } } };
vm.runInNewContext(fs.readFileSync('js/shared/dashboard-league-layout.js', 'utf8'), { window, Date: { now: () => now } });
const layout = window.App.DashboardLeagueLayout;
const original = [{ id: 'custom1', key: 'market-radar', size: 'lg' }, { id: 'custom2', key: 'league-standings', size: 'md' }];
const migrated = layout.addMissing(original);
assert.equal(migrated.length, 5);
assert.equal(migrated[3], original[0]);
assert.equal(migrated[4], original[1]);
assert.equal(migrated.filter(w => w.key === 'league-standings').length, 1);
assert.deepEqual(layout.addMissing(migrated), migrated);
assert.equal(original.length, 2);
assert.notEqual(layout.defaults()[0], layout.defaults()[0]);
assert.notEqual(layout.marker('123'), layout.marker('456'));
assert.equal(layout.leagueId({ league_id: '123' }), '123');
assert.equal(layout.request('stats', '123'), false);
assert.equal(events.length, 0);
assert.equal(layout.request('league-cup', '123'), true);
assert.equal(events[0].type, 'wr:league-central-nav');
assert.equal(layout.peek('456'), null);
assert.equal(layout.consume('123').section, 'cup');
assert.equal(layout.consume('123'), null);
layout.request('league-standings', 123);
assert.equal(layout.consume('123').anchor, 'standings');
layout.request('weekly-matchups', '123');
assert.equal(layout.peek('123').anchor, 'scoreboard');
now += 30001;
assert.equal(layout.peek('123'), null);
console.log('Dashboard layout: preserved order, deduplication, scoped migration and direct navigation passed.');
