const assert = require('node:assert/strict');
require('../js/shared/stat-catalog.js');
require('../js/shared/league-stats.js');
require('../js/shared/fa-market-data.js');
const M = globalThis.App.FAMarketData;

const qb = { gp: 4, pass_cmp: 60, pass_att: 100, pass_yd: 850, cmp_pct: 240, pass_ypa: 34 };
assert.equal(M.signature('QB', 0, qb).value, 0.6, 'completion percentage derives from season counts');
assert.equal(M.signature('QB', 0, qb).text, '60.0%');
assert.equal(M.signature('QB', 1, qb).value, 8.5, 'YPA is not divided by games played');
assert.equal(M.signature('QB', 1, qb).short, 'YPA');
assert.equal(M.signature('QB', 1, qb).label, 'Yards / Attempt');
const targets = M.signature('WR', 0, { gp: 4, rec_tgt: 13 });
assert.equal(targets.value, 3.25);
assert.equal(targets.text, '3.3');
assert.equal(targets.label, 'Targets per game');
assert.equal(targets.short, 'TGT/G');
const snaps = M.signature('WR', 1, { gp: 4, off_snp: 90, tm_off_snp: 200 });
assert.equal(snaps.value, 0.45);
assert.equal(snaps.text, '45.0%');
assert.equal(snaps.short, 'SNP%');
const tackles = M.signature('DE', 0, { gp: 2, idp_tkl_solo: 0, idp_tkl_ast: 0 });
assert.equal(tackles.value, 0);
assert.equal(tackles.text, '0.0');
assert.equal(tackles.short, 'TKL/G');
assert.equal(M.signature('WR', 0, { rec_tgt: 13 }).value, null, 'per-game count requires games played');
assert.equal(M.signature('WR', 0, { rec_tgt: 13 }).text, '—');
assert.equal(M.signature('WR', 0, { gp: 3, rec_tgt: 'invalid' }).value, null);
assert.equal(M.signature('QB', 1, { pass_yd: 120, pass_att: 10 }).value, 12, 'efficiency rate does not need games played');
assert.equal(M.signature('DEF', 0, {}), null, 'no invented signature for unsupported position');
assert.equal(M.ppg({ gp: 2, pass_int: 0 }, { pass_int: -2 }, 'QB'), 0);
assert.equal(M.ppg({ gp: 3, pass_int: 2 }, { pass_int: -2 }, 'QB'), -1.3);
assert.equal(M.ppg({ gp: 0, rec: 5 }, { rec: 1 }, 'WR'), null);
assert.equal(M.ppg({ rec: 5 }, { rec: 1 }, 'WR'), null);
assert.equal(M.ppg({ gp: 2, rec: 5 }, {}, 'WR'), null);
assert.equal(M.ppg({ gp: 2, sack: 1 }, { sack: 1, idp_sack: 4 }, 'LB'), 2, 'league-scored PPG keeps IDP namespace');
assert.deepEqual(M.recentPpg([{ week: 1, pts: 10 }, { week: 2, pts: 0 }, { week: 3, pts: -1 }, { week: 4, pts: 99 }, { week: 5, pts: 0 }], 4, 3), { value: 3, count: 3 }, 'recent average retains zero/negative outcomes and excludes incomplete/future weeks');
assert.deepEqual(M.recentPpg([{ week: 1, pts: 40 }, { week: 2, pts: 10 }, { week: 3, pts: 14 }, { week: 4, pts: NaN }], 5, 2), { value: 12, count: 2 }, 'lookback uses the latest reported completed weeks');
assert.equal(M.recentPpg([{ week: 1, pts: 0 }], 1, 3), null);
console.log('FA market data: season rates, per-game usage, zero/missing, precision, league scoring and completed-week averages passed.');
