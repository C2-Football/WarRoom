#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const src = fs.readFileSync('js/free-agency.js', 'utf8');
const start = src.indexOf('    function buildFaRosterRead(');
const end = src.indexOf('    window.App.buildFaRosterRead =', start);
const ctx = vm.createContext({});
vm.runInContext(src.slice(start, end), ctx);
const players = { q1: { position: 'QB', full_name: 'Mahomes' }, q2: { position: 'QB', full_name: 'Stafford' }, r1: { position: 'RB' }, r2: { position: 'RB' }, w1: { position: 'WR' }, w2: { position: 'WR' }, te: { position: 'TE' }, k: { position: 'K' }, def: { position: 'DEF' } };
const values = { q1: 3000, q2: 2400, r1: 3000, r2: 2000, w1: 2500, w2: 500, te: 2000, k: 1000, def: 1000 };
const league = { roster_positions: ['QB','RB','WR','TE','FLEX','K','DEF','BN','BN'] };
const roster = { players: Object.keys(players) };
const read = () => ctx.buildFaRosterRead(roster, league, players, pid => values[pid]);
let result = read();
assert.equal(result.known, true);
assert.equal(result.coverage, 7);
assert.equal(result.fit('QB', 1784).short, 'Covered');
assert.equal(result.fit('QB', 1784).score, 0);
assert.equal(result.rows.find(r => r.pos === 'QB').actual, 2);
assert.equal(result.rows.find(r => r.pos === 'QB').required, 1);
assert.equal(result.fit('DEF', 800).short, 'Covered');
assert.equal(result.fit('K', 1100).gain, 100, 'gain is incremental, not whole free-agent value');
assert.equal(result.fit('WR', 900).gain, 400);
assert.equal(result.fit('QB', 2600).gain, 200, 'a genuine same-position upgrade survives');
const sf = ctx.buildFaRosterRead({ players: ['q1','r1','w1'] }, { roster_positions: ['QB','RB','WR','SUPER_FLEX'] }, players, pid => values[pid]);
assert.equal(sf.coverage, 3, 'a player cannot fill two slots');
assert.equal(sf.fit('QB', 100).short, 'Open slot');
const missing = ctx.buildFaRosterRead({ players: ['missing'] }, league, players, () => 0);
assert.equal(missing.known, false);
assert.equal(missing.fit('QB', 9999).score, 0, 'unknown roster never invents a need');
values.q2 = 0;
assert.equal(read().fit('QB', 1784).gain, null, 'missing roster value does not manufacture an upgrade');
assert.equal(ctx.buildFaRosterRead({ players: ['q1', 'q1'] }, league, players, pid => values[pid]).owned.length, 1, 'duplicate IDs counted once');
console.log('PASS free agency: actual roster coverage, FLEX matching, QB fit, value deltas, incomplete data');
