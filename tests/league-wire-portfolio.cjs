'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const leagues = ['a', 'b', 'c'].map(id => ({ id, season: '2026', name: 'League ' + id, settings: { playoff_week_start: 15 }, rosters: [{ roster_id: 1, owner_id: id + '1' }, { roster_id: 2, owner_id: id + '2' }], users: [] }));
const root = { console, setTimeout, clearTimeout, S: {} }; root.window = root; vm.createContext(root);
for (const f of ['league-live-scores', 'league-live-table', 'league-wire-journal', 'league-wire-portfolio']) vm.runInContext(fs.readFileSync(`js/shared/${f}.js`, 'utf8'), root);
const api = root.WrWirePortfolio;
const calls = []; const timeline = [];
const fetcher = async url => { calls.push(url); if (url.includes('/state/')) return { ok: true, json: async () => ({ season: '2026', season_type: 'regular', week: 2 }) }; const id = url.split('/league/')[1]?.split('/')[0]; if (url.endsWith('/' + id)) return { ok: true, json: async () => ({ previous_league_id: null }) }; return { ok: true, json: async () => [{ roster_id: 1, points: id === 'a' ? 120 : id === 'b' ? 100 : 90, matchup_id: 1 }, { roster_id: 2, points: 80, matchup_id: 1 }] }; };
(async () => {
    const state = {};
    await api.load({ leagues, accountId: 'user1', fetcher, onUpdate: e => { state[e.league.id] = e; timeline.push([e.league.id, e.currentReady, e.status]); } });
    assert.equal(Object.keys(state).length, 3);
    assert(Object.values(state).every(e => e.status === 'ready'));
    assert(timeline.findIndex(([id, ready]) => id === 'c' && ready) < timeline.findIndex(([, , status]) => status === 'ready'), 'all current editions arrive before the historical queue completes');
    const headlines = api.headlines(Object.values(state));
    assert.equal(new Set(headlines.slice(0, 3).map(s => s.league.id)).size, 3, 'front page gives each league a turn');
    const recaps = api.headlines(Object.values(state), 'recaps', 'b');
    assert(recaps.length); assert(recaps.every(s => s.league.id === 'b' && s.kind === 'recap'));
    const archived = { ...state.a, stories: state.a.stories.concat({ id: 'old-title', text: 'Old title', documentary: true, eventSeason: 2024, weight: 999 }) };
    assert(!api.headlines([archived]).some(s => s.documentary), 'archive facts cannot compete for current multi-league headlines');
    assert(api.headlines([archived], 'history').some(s => s.id === 'old-title'));
    assert.equal(api.lookback([archived]).id, 'old-title');
    assert.equal(api.lookback([archived], 'b'), null, 'lookbacks respect the league filter');
    assert.equal(api.headlines([{ ...state.a, historical: true }]).length, 0, 'past connected seasons are not current headlines');
    assert(api.headlines([{ ...state.a, historical: true }], 'history').every(s => s.documentary), 'past editions stay available as labeled history');
    const before = calls.length;
    await api.load({ leagues, accountId: 'user1', fetcher, onUpdate() {} });
    assert.equal(calls.length - before, 1, 'warm combined edition only checks the calendar');
    const next = calls.length;
    await api.load({ leagues, accountId: 'user2', fetcher, onUpdate() {} });
    assert(calls.length - next > 1, 'account change does not reuse previous account edition');
    const partial = {};
    await api.load({ leagues, accountId: 'user3', force: true, fetcher: async url => url.includes('/league/b/') ? { ok: false } : fetcher(url), onUpdate: e => partial[e.league.id] = e });
    assert.equal(partial.b.status, 'partial'); assert.equal(partial.a.status, 'ready'); assert.equal(partial.c.status, 'ready');
    const ended = new AbortController(); ended.abort(); let updates = 0;
    await api.load({ leagues, signal: ended.signal, fetcher, onUpdate: () => updates++ }); assert.equal(updates, 0);
    assert.equal(api.period({ ...leagues[0], season: '2025' }, { season: '2026', week: 2 }).end, 14);
    assert.equal(api.period(leagues[0], { season: '2026', season_type: 'pre', week: 4 }).end, 0);
    const ui = fs.readFileSync('js/components/league-wire-portfolio.js', 'utf8');
    assert(ui.includes('showModal()') && ui.includes('onCancel={onClose}') && ui.includes('opener.current?.isConnected'));
    assert(fs.readFileSync('js/app.js', 'utf8').includes('onOpenAllWire={() => setAllWireOpen(true)}'));
    console.log('PASS all-league Wire: progressive current editions, fair league coverage, filters, account scope, cache reuse, partial failures and cancellation');
})().catch(error => { console.error(error); process.exitCode = 1; });
