'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync('js/shared/lineup-forecast-snapshots.js', 'utf8'), context);
const { createStore } = context.window.App.LineupForecastSnapshots;
const disk = new Map();
const storage = { getItem: key => disk.get(key), setItem: (key, value) => disk.set(key, value) };
let store = createStore(storage);
const league = { league_id: '123', season: '2026' };
const input = { league, week: 1, projections: { a: 15.5, b: 0, c: -1, absent: null, unknown: 9 }, statuses: { a: 'upcoming', b: 'live', c: 'final', absent: 'upcoming', unknown: 'unknown' }, now: 1000 };
const first = store.capture(input);
assert.equal(first.players.a.kind, 'pregame');
assert.equal(first.players.b.kind, 'first-view');
assert.equal(first.players.b.points, 0);
assert.equal(first.players.c.points, -1);
assert.equal(first.players.absent, undefined);
assert.equal(first.players.unknown, undefined);
assert.equal(first.persistent, true);
const refreshed = store.capture({ ...input, now: 2000, projections: { a: 99, b: 99 }, statuses: { a: 'final', b: 'final' } });
assert.equal(refreshed.players.a.points, 15.5);
assert.equal(refreshed.players.a.capturedAt, 1000);
assert.equal(refreshed.players.a.kind, 'pregame');
store = createStore(storage); // Reopen browser/module.
assert.equal(store.read(league, 1).players.a.points, 15.5);
assert.equal(Object.keys(store.read(league, 2).players).length, 0);
assert.equal(Object.keys(store.read({ ...league, season: 2025 }, 1).players).length, 0);
assert.equal(Object.keys(store.read({ ...league, league_id: '456' }, 1).players).length, 0);
const denied = createStore({ getItem() { throw Error('denied'); }, setItem() { throw Error('denied'); } });
assert.equal(denied.capture(input).persistent, false);
assert.equal(denied.capture({ ...input, projections: { a: 99 } }).players.a.points, 15.5);
const corrupt = createStore({ getItem: () => '{bad json', setItem() {} });
assert.equal(corrupt.capture(input).players.a.points, 15.5);
console.log('PASS stable lineup forecasts: frozen values, pregame/first-view labels, reopen persistence, scope isolation, unavailable and denied storage');
