'use strict';
const assert = require('node:assert/strict');
require('../js/shared/scoring-visuals.js');
const V = globalThis.App.ScoringVisuals;
assert.equal(V.completedWeekLimit(2026, { season: 2026, week: 6, season_type: 'regular' }), 5);
assert.equal(V.completedWeekLimit(2026, { season: 2026, week: 7, display_week: 6, season_type: 'regular' }), 5, 'the currently displayed week stays ungraded during provider rollover');
assert.equal(V.completedWeekLimit(2026, { season: 2026, week: 1, season_type: 'pre' }), 0);
assert.equal(V.completedWeekLimit(2026, { season: 2026, week: 1, season_type: 'post' }), 18);
assert.equal(V.completedWeekLimit(2025, { season: 2026, week: 6 }), 18);
assert.equal(V.completedWeekLimit(2027, { season: 2026, week: 6 }), 0);
assert.equal(V.completedWeekLimit(2026, {}), 0, 'unknown NFL context cannot certify a completed week');
assert.equal(V.summarize([null, undefined, '2', 0, -2]), null);
assert.deepEqual(V.summarize([0, 10, 20, 30, null]), { median: 15, count: 4, band: 3 });
const baseline = V.summarize([10, 10, 10]);
assert.equal(V.classify(13, baseline).tone, 'strong');
assert.equal(V.classify(12, baseline).tone, 'typical', 'threshold includes its boundary');
assert.equal(V.classify(0, baseline).tone, 'quiet', 'true zero stays meaningful');
assert.equal(V.classify(-2, baseline).tone, 'quiet');
assert.equal(V.classify(50, baseline, { complete: false }).tone, 'neutral', 'unfinished points never receive a result grade');
assert.equal(V.classify(null, baseline).tone, 'neutral');
assert.equal(V.classify(20, null).tone, 'neutral', 'small samples remain ungraded');
assert.equal(V.compare(0, 3, { lowerIsBetter: true }).tone, 'strong', 'fewer interceptions is better');
assert.equal(V.compare(0, 0).tone, 'typical', 'zero baseline never divides by zero');
assert.equal(V.compare(-4, -1).tone, 'quiet', 'negative baseline uses signed point difference');
console.log('PASS scoring visuals: completed-week boundaries, finite samples, robust median bands, inverse stats and zero/negative/unavailable/live values.');
