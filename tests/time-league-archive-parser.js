'use strict';
const assert = require('node:assert/strict');
global.window = globalThis;
global.App = {};
for (const name of ['roster', 'draft-room', 'season']) require('../js/shared/time-league-' + name + '.js');
const parse = App.TimeLeagueSeason.parseGameLogCsv;
const header = 'player,pos,season,week,passyd,fgm,source_game_id,scheduled_games,historical_week,source_week_kind';
const quoted = '"A ""Quoted"",\nName",QB,2023,18,80,1,"game,18",17,18,nfl-week';
const parsed = parse(header + '\r\n' + quoted + '\r\n' + quoted.replace(',80,1,', ',20,2,') + '\r\n');
assert.equal(parsed.logs.length, 1, 'Quoted commas and newlines remain within a single player record');
assert.equal(parsed.logs[0].name, 'A "Quoted",\nName');
assert.equal(parsed.logs[0].stats.passYd, 100, 'Split exports still merge production');
assert.equal(parsed.logs[0].stats.extra.fgm, 3);
assert.equal(parsed.logs[0].sourceGameId, 'game,18');
assert.equal(parsed.logs[0].scheduledGames, 17);
assert.equal(parsed.logs[0].historicalWeek, 18);
assert.equal(parsed.logs[0].sourceWeekKind, 'nfl-week');
assert.equal(parse('wrong,header\nfirst,row\nsecond,row').skippedRows, 2);
assert.deepEqual(parse(''), { logs: [], skippedRows: 0 });
assert.deepEqual(parse(header), { logs: [], skippedRows: 0 });
assert.throws(() => parse('player,pos,season,week\n' + 'Bad,,2023,1\n'.repeat(1000001)), /one-million-row limit/, 'Oversized archives fail explicitly rather than silently dropping a tail');
console.log('PASS: streaming CSV quotes, multiline cells, duplicate scoring, source metadata and explicit row bound');
