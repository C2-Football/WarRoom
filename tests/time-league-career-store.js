'use strict';
const assert = require('assert');
global.window = globalThis;
global.App = {};
const disk = new Map();
global.localStorage = { getItem:key=>disk.get(key)||null, setItem:(key,value)=>disk.set(key,value) };
let userId = 'alice';
App.OD = {getCurrentUserId:()=>userId};
App.TimeLeagueCareer = require('../js/shared/time-league-career.js');
const Store = require('../js/shared/time-league-career-store.js');
const league = { leagueId:'one', name:'History', createdAt:'2026-01-01', phase:'complete', championTeamId:'alice', settings:{regularSeasonWeeks:1}, teams:[{teamId:'alice',name:'Alice',manager:'human'},{teamId:'bob',name:'Bob',manager:'human'}], draftPicks:[], finalizedWeeks:[{week:1,results:[{teamId:'alice',total:20},{teamId:'bob',total:10}],matchups:[{home:'alice',away:'bob',homePoints:20,awayPoints:10,winner:'alice'}]}] };
Store.remember(league,{seatTeamId:'alice',rowId:'remote'});
assert.equal(Store.read('account:alice')[0].stats.trophies,1);
assert.equal(Store.read('account:bob').length,0);
userId = 'bob';
Store.remember(league,{seatTeamId:'bob',rowId:'remote'});
assert.equal(Store.read('account:bob')[0].stats.trophies,0);
assert.equal(Store.read('account:bob')[0].stats.points,10);
assert.equal(Store.read('account:alice')[0].stats.points,20);
Store.remember({...league,leagueId:'wrong-account'},{seatTeamId:'alice',rowId:'remote',userId:'alice'});
assert.equal(Store.read('account:bob').length,1);
Store.remember({...league,leagueId:'missing-seat'},{rowId:'remote',userId:'bob'});
assert.equal(Store.read('account:bob').length,1);
userId = null;
Store.remember({...league,leagueId:'logged-out'},{seatTeamId:'alice',rowId:'remote'});
assert.equal(Store.read('account:null').length,0);
Store.remember(league);
assert.equal(Store.read('solo:device').length,1);
Store.remember(league,null,true); // Archive before the league save is removed.
assert.equal(Store.read('solo:device')[0].archived,true);
assert.equal(App.TimeLeagueCareer.summarize(Store.read('solo:device')).overall.trophies,1);
Store.remember({...league,phase:'season',championTeamId:undefined});
assert.equal(Store.read('solo:device').length,1);
assert.equal(Store.read('solo:device')[0].archived,false);
assert.equal(Store.read('solo:device')[0].stats.trophies,0);
assert.equal(Store.read('solo:device')[0].stats.completed,0);
assert.equal(Store.read('account:alice')[0].stats.trophies,1);
console.log('Career store: account separation, signed-out guard, archive persistence, refresh and reopened playoffs passed.');
