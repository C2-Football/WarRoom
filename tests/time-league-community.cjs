'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
    const M = await import('../supabase/functions/time-league/community-model.mjs');
    const modelUrl = require('node:url').pathToFileURL(require('node:path').resolve('supabase/functions/time-league/community-model.mjs')).href;
    const source = fs.readFileSync('supabase/functions/time-league/community.ts', 'utf8').replace("'./community-model.mjs'", JSON.stringify(modelUrl));
    const compiled = require('@babel/standalone').transform(source, { filename: 'community.ts', presets: ['typescript'] }).code;
    const { handleCommunity } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
    const user = '12345678-1234-1234-1234-123456789000';
    const publicId = '12345678-1234-1234-1234-123456789001';
    const profile = { displayName: '  The  Manager ', teamName: ' Test Club ', primaryColor: '#001122', secondaryColor: '#ffffff', backdrop: 'heritage', helmet: { safe: true }, publicProfile: false, lookingForLeague: false };
    const normalizeHelmet = () => ({ normalized: true });
    const clean = M.normalizeProfileInput({ ...profile, user_id: 'attack', profileId: 'attack', stats: { wins: 10000 }, email: 'hidden@example.test' }, normalizeHelmet);
    assert.equal(clean.identity.displayName, 'The Manager');
    assert.deepEqual(Object.keys(clean), ['identity', 'public_profile', 'looking_for_league']);
    assert.equal(JSON.stringify(clean).includes('attack'), false); assert.equal(JSON.stringify(clean).includes('email'), false);
    assert.deepEqual(clean.identity.helmet, { normalized: true });
    for (const invalid of [{ publicProfile: 'true' }, { publicProfile: false, lookingForLeague: true }, { backdrop: 'url(javascript:bad)' }, { primaryColor: 'red' }, { displayName: 'a'.repeat(41) }]) assert.throws(() => M.normalizeProfileInput({ ...profile, ...invalid }, normalizeHelmet));
    assert.equal(M.projectProfile(null), null);
    const safe = M.projectDirectoryRow({ user_id: user, email: 'secret', invite_code: 'secret', profile_id: publicId, identity: { ...clean.identity, email: 'secret' }, looking_for_league: true, wins: '4', games: 6 });
    assert.equal(safe.stats.wins, 4); assert.equal(safe.profileId, publicId); assert.equal(JSON.stringify(safe).includes('secret'), false);
    assert.deepEqual(M.directoryInput({ limit: 10000, page: -2, view: 'leaderboard', q: "%'\"(),.*!Hello" }), { limit: 50, page: 0, q: 'Hello', leaderboard: true, lookingOnly: false });
    assert.throws(() => M.publicId('bad', 'manager'));
    console.log('ok profile validation strips spoofed ownership and scores, bounds inputs, and projects public fields');
    const calls = [];
    function query(result) {
        const proxy = new Proxy({}, { get: (_, key) => key === 'then' ? resolve => resolve(result) : (...args) => { calls.push([key, ...args]); return proxy; } });
        return proxy;
    }
    let result = { data: { profile_id: publicId, ...clean }, error: null };
    const admin = { from: name => { calls.push(['from', name]); return query(result); }, rpc: async (name, args) => { calls.push(['rpc', name, args]); return result; } };
    await handleCommunity(admin, user, { op: 'profile-save', profile: { ...profile, user_id: 'attack' } }, normalizeHelmet);
    assert.equal(calls.find(c => c[0] === 'upsert')[1].user_id, user);
    calls.length = 0;
    await handleCommunity(admin, user, { op: 'profile-get', userId: 'attack' }, normalizeHelmet);
    assert(calls.some(c => c[0] === 'eq' && c[1] === 'user_id' && c[2] === user));
    calls.length = 0; result = { data: publicId, error: null };
    await handleCommunity(admin, user, { op: 'community-invite', rowId: publicId, profileId: publicId, seatTeamId: 't2', userId: 'attack' }, normalizeHelmet);
    assert.equal(calls[0][2].p_user_id, user);
    calls.length = 0;
    await handleCommunity(admin, user, { op: 'community-respond', inviteId: publicId, accept: true, userId: 'attack' }, normalizeHelmet);
    assert.equal(calls[0][2].p_user_id, user);
    await assert.rejects(() => handleCommunity(admin, user, { op: 'community-respond', inviteId: publicId, accept: 'true' }, normalizeHelmet));
    console.log('ok profile saves and invitation RPCs always use verified session ownership');
    calls.length = 0; result = { data: Array.from({ length: 3 }, () => ({ profile_id: publicId, identity: clean.identity, games: 1 })), error: null };
    const listing = await handleCommunity(admin, user, { op: 'community-list', view: 'leaderboard', page: 1, limit: 2, lookingOnly: true, q: 'Name' }, normalizeHelmet);
    assert.equal(listing.profiles.length, 2); assert.equal(listing.hasMore, true);
    assert(calls.some(c => c[0] === 'from' && c[1] === 'time_league_public_directory'));
    assert(calls.some(c => c[0] === 'or' && c[1].includes('displayName') && c[1].includes('teamName')));
    assert(calls.some(c => c[0] === 'gt' && c[1] === 'games' && c[2] === 0));
    assert(calls.some(c => c[0] === 'range' && c[1] === 2 && c[2] === 4));
    assert(calls.some(c => c[0] === 'eq' && c[1] === 'looking_for_league' && c[2] === true));
    const inviteRow = { id: publicId, league_id: publicId, seat_team_id: 't2', sender_id: publicId, recipient_id: user, status: 'pending', created_at: '2026-09-07T00:00:00Z', time_leagues: { name: 'Friends', phase: 'draft', draft_started: false } };
    const inviteAdmin = { from: table => query({ error: null, data: table === 'time_league_community_invites' ? [inviteRow] : table === 'time_league_members' ? [{ league_id: publicId, seat_team_id: 't2', user_id: 'occupied' }] : [{ user_id: publicId, profile_id: publicId, identity: clean.identity }] }) };
    const inbox = await handleCommunity(inviteAdmin, user, { op: 'community-invites' }, normalizeHelmet);
    assert.equal(inbox.incoming[0].available, false);
    assert.equal(inbox.incoming[0].from.displayName, 'The Manager');
    assert.equal(inbox.outgoing.length, 0);
    assert.equal(JSON.stringify(inbox).includes('sender_id'), false);
    assert.equal(JSON.stringify(inbox).includes('user_id'), false);
    console.log('ok invitation inbox excludes ownership IDs and marks occupied seats unavailable');
    const edge = fs.readFileSync('supabase/functions/time-league/index.ts', 'utf8');
    assert(edge.indexOf('if (!session)') < edge.indexOf('await handleCommunity'));
    console.log('ok directory uses opt-in server view with bounded pages and verified results only');
    console.log('PASS: Vault community request and response boundaries');
})().catch(error => { console.error(error); process.exitCode = 1; });
