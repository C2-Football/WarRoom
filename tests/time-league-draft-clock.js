'use strict';
const assert = require('node:assert/strict');
global.window = globalThis;
global.App = {};
for (const name of ['roster','rules','draft-room','era-rules','season','helmet','engine','ai','actions','draft-clock']) require('../js/shared/time-league-' + name + '.js');
const { TimeLeagueEngine: E, TimeLeagueActions: A, TimeLeagueDraftClock: Clock } = App;
const origin = Date.parse('2026-09-07T12:00:00Z');
const stamp = seconds => new Date(origin + seconds * 1000).toISOString();
const cards = new Map(Array.from({ length: 12 }, (_, i) => {
    const identity = 'qb' + i;
    return [identity, { identity, name: 'Quarterback ' + i, position: 'QB', peak: 200 - i * 3, seasons: [{ season: 2000, points: 200 - i * 3, games: 16 }] }];
}));
const create = patch => E.createTimeLeague({ name: 'Clock room', seed: 'clock', createdAt: stamp(0), seats: [{ name: 'You', manager: 'human' }, { name: 'Rival', manager: 'ai', aiPersona: 'warlord' }], settings: { rosterSlots: { QB: 1 }, regularSeasonWeeks: 12, scoring: { passTd: 4, reception: 0.5, rushRecYd: 0.1, passingYd: 0.04, turnover: -2 }, maxQuarterbacks: 1, eraRules: { mode: 'any-era', decades: [] }, draftPickSeconds: 15, draftAiSeconds: 2, ...patch } });
const apply = (state, action, seconds, teamId = 't1') => A.applyOnlineAction(state, action, { seat_team_id: teamId, role: 'commissioner' }, { cards }, stamp(seconds));
let state = create();
assert.equal(Clock.nextAction(state, cards, origin + 60000), null, 'Time in the ceremony cannot take picks');
state = apply(state, { type: 'draft-clock-start' }, 0);
assert.equal(Clock.nextAction(state, cards, origin + 30000, false), null, 'A client with sealed reveals cannot drive the room');
assert.equal(Clock.nextAction(state, cards, origin + 14999), null, 'Human picks remain under their control before timeout');
const expired = Clock.nextAction(state, cards, origin + 15000);
assert.deepEqual(expired, { type: 'draft-timeout' });
state = apply(state, expired, 15);
assert.equal(state.draftPicks.length, 1, 'The driver emits the actual authorized timeout action');
assert.equal(Clock.nextAction(state, cards, origin + 16999), null);
const auto = Clock.nextAction(state, cards, origin + 17000);
assert.deepEqual(auto, { type: 'draft-ai-step' });
state = apply(state, auto, 17);
assert.equal(state.phase, 'season', 'The timed human pick and paced AI pick complete a real draft');
assert.equal(Clock.nextAction(state, cards, origin + 50000), null);

state = apply(create(), { type: 'draft-clock-start' }, 0);
state = apply(state, { type: 'draft-clock-pause' }, 5);
assert.equal(Clock.nextAction(state, cards, origin + 1000000), null, 'Pause survives long periods without advancing');
state = E.normalizeTimeLeague(JSON.parse(JSON.stringify(state)));
state = apply(state, { type: 'draft-clock-resume' }, 1000);
assert.equal(Clock.nextAction(state, cards, origin + 1009999), null);
assert.deepEqual(Clock.nextAction(state, cards, origin + 1010000), { type: 'draft-timeout' }, 'Resume retains the remaining time after reload');

state = apply(create({ draftFormat: 'auction', draftPickSeconds: 0, draftAuctionBudget: 20 }), { type: 'draft-clock-start' }, 0);
state = apply(state, { type: 'auction-nominate', teamId: 't1', identity: 'qb0', amount: 1 }, 1);
assert.equal(Clock.nextAction(state, cards, origin + 2999), null);
assert.deepEqual(Clock.nextAction(state, cards, origin + 3000), { type: 'auction-ai-step' });
state = apply(state, Clock.nextAction(state, cards, origin + 3000), 3);
assert.equal(state.draftAuction.nomination.highTeamId, 't2', 'The AI actually competes at the selected pace');
assert.equal(Clock.nextAction(state, cards, origin + 6000), null, 'The sole leading AI does not bid against itself');
const savedAi = App.TimeLeagueAI.aiAuctionStep;
App.TimeLeagueAI.aiAuctionStep = () => { throw Error('No-change auction should be cached until room changes'); };
assert.equal(Clock.nextAction(state, cards, origin + 7000), null);
App.TimeLeagueAI.aiAuctionStep = savedAi;
console.log('PASS: draft driver honors reveal, human deadline, AI pace, pause/reload, auction competition, completion and no-op caching.');
