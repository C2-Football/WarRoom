'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
global.App = {};
for (const name of ['roster', 'rules', 'draft-room', 'era-rules', 'season', 'helmet', 'engine', 'ai', 'rivals']) require(`../js/shared/time-league-${name}.js`);
(async () => {
    const source = fs.readFileSync('supabase/functions/time-league/messages.ts', 'utf8');
    const compiled = require('@babel/standalone').transform(source, { filename: 'messages.ts', presets: ['typescript'] }).code;
    const { sendPrivateMessage, loadPrivateMessages, withoutPrivateMessages } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
    const R = App.TimeLeagueRivals;
    const stamp = '2026-09-07T12:00:00.000Z';
    const state = App.TimeLeagueEngine.createTimeLeague({ name: 'Private chat', seed: 'chat', createdAt: stamp,
        settings: { rosterSlots: { QB: 1, BN: 1 }, eraRules: { mode: 'any-era', decades: [] } },
        seats: [{ name: 'Host', manager: 'human' }, { name: 'Friend', manager: 'human' }, { name: 'Other', manager: 'human' }, { name: 'Rival', manager: 'ai', aiPersona: 'warlord' }] });
    const row = { id: 'row-id', state: { ...state, phase: 'complete', currentWeek: 14, rivalMessages: [{ text: 'never shared' }] }, version: 12, draft_started: false };
    const members = state.teams.filter(t => t.manager === 'human').map((t, i) => ({ user_id: `u${i}`, seat_team_id: t.teamId, joined_at: stamp, role: i ? 'member' : 'commissioner' }));
    const member = members[0]; const ownId = member.seat_team_id; const friendId = members[1].seat_team_id; const aiId = state.teams.find(t => t.manager === 'ai').teamId;
    const calls = []; let history = []; let result = { ok: true, version: 13 };
    const admin = { rpc: async (name, params) => { calls.push({ name, params }); return { data: name === 'load_time_league_messages' ? history : result, error: null }; } };
    const action = { type: 'rival-message', toTeamId: friendId, text: '  Good game!  ', tone: 'friendly', messageId: 'send_00000001' };
    const send = (patch = {}, options = {}) => sendPrivateMessage(admin, 'u0', options.row || row, options.member || member, options.members || members, { ...action, ...patch }, R, options.version ?? 12, stamp);
    assert.deepEqual(withoutPrivateMessages(row.state).rivalMessages, undefined);
    assert.equal(row.state.rivalMessages[0].text, 'never shared', 'shared projection does not mutate its input');
    assert.deepEqual(await loadPrivateMessages(admin, 'u0', 'row-id'), []);
    assert.deepEqual(calls.at(-1).params, { p_user_id: 'u0', p_league_id: 'row-id', p_limit: 1000 });
    calls.length = 0;
    assert.deepEqual(await send(), result, 'closed leagues and unopened draft rooms may still have conversations');
    const args = calls.at(-1).params;
    assert.equal(calls.at(-1).name, 'send_time_league_message');
    assert.equal(args.p_user_id, 'u0'); assert.equal(args.p_expected_version, 12);
    assert.equal(args.p_messages.length, 1, 'a human DM never fabricates an AI reply');
    assert.equal(args.p_relationship, null);
    assert.deepEqual(args.p_messages[0], { id: 'chat:send_00000001', fromTeamId: ownId, toTeamId: friendId, text: 'Good game!', tone: 'friendly', week: 14, createdAt: stamp, sequence: 1 });
    assert.equal(Object.keys(args).some(key => key === 'p_state'), false, 'the helper cannot send a whole replacement game snapshot');
    await send({ toTeamId: aiId, tone: 'competitive', messageId: 'send_00000002', createdAt: '1900-01-01', fromTeamId: friendId });
    const ai = calls.at(-1).params;
    assert.equal(ai.p_messages.length, 2);
    assert.equal(ai.p_messages[1].id, 'reply:send_00000002');
    assert.equal(ai.p_messages[1].fromTeamId, aiId);
    assert.equal(ai.p_messages[1].toTeamId, ownId);
    assert.equal(ai.p_messages[0].createdAt, stamp, 'client-provided timestamps are ignored');
    assert.deepEqual(ai.p_relationship, { ownerTeamId: aiId, otherTeamId: ownId, heat: 2, updatedWeek: 14 });
    const postgameRow = { ...row, state: { ...row.state, phase: 'season', weekStage: 'postgame', currentWeek: 2 } };
    await send({ toTeamId: aiId, messageId: 'postgame_00001' }, { row: postgameRow });
    assert(calls.at(-1).params.p_messages.every(message => message.week === 1), 'Private online postgame replies use the same visible week as solo');
    assert.equal(calls.at(-1).params.p_relationship.updatedWeek, 2, 'The server retains the internal relationship decay clock');
    await send({ toTeamId: aiId, messageId: 'postgame_00002' }, { row: { ...postgameRow, state: { ...postgameRow.state, weekStage: 'claims' } } });
    assert(calls.at(-1).params.p_messages.every(message => message.week === 2), 'Online replies advance with the weekly gate');
    console.log('ok messages use verified ownership, server time and private RPCs, with AI-only reactions');
    for (const patch of [{ teamId: friendId }, { toTeamId: ownId }, { toTeamId: 'missing' }, { text: '' }, { text: 'a'.repeat(501) }, { tone: 'threat' }, { messageId: 'tiny' }, { messageId: 'bad:id-12345' }, { replyToId: 44 }]) {
        const count = calls.length;
        await assert.rejects(() => send(patch));
        assert.equal(calls.length, count, 'invalid input is rejected before any database read or mutation');
    }
    await assert.rejects(() => send({}, { member: { ...member, user_id: 'impostor' } }), /joined seat/);
    await assert.rejects(() => send({}, { member: { ...member, joined_at: null } }), /joined seat/);
    await assert.rejects(() => send({}, { members: members.map((m, i) => i === 1 ? { ...m, joined_at: null } : m) }), /not joined/);
    history = [{ ...args.p_messages[0], id: 'chat:private_0001', toTeamId: members[2].seat_team_id }];
    await assert.rejects(() => send({ replyToId: 'chat:private_0001' }), /not part of this conversation/);
    await assert.rejects(() => send({ replyToId: 'game:14:another-seat' }), /not part of this conversation/);
    history = [args.p_messages[0]];
    await send({ messageId: 'send_00000003', replyToId: 'chat:send_00000001' });
    assert.equal(calls.at(-1).params.p_messages[0].replyToId, 'chat:send_00000001');
    assert.equal(calls.at(-2).params.p_reply_id, 'chat:send_00000001', 'authored replies pin their original message before model validation');
    calls.length = 0;
    await loadPrivateMessages(admin, 'u0', 'row-id', 'send_00000004', 'game:14:t1');
    assert.equal(Object.hasOwn(calls[0].params, 'p_reply_id'), false, 'derived event replies do not request authored-history pins');
    result = { ok: true, version: 19, deduplicated: true };
    await send({}, { version: 1 });
    assert.equal(calls.at(-1).params.p_expected_version, 1, 'exact retries reach the locked RPC even with a stale client version');
    await assert.rejects(() => send({ text: 'different content' }), /already used/);
    result = { ok: false, conflict: true }; history = [];
    assert.deepEqual(await send(), result, 'ordinary CAS conflicts propagate without an optimistic success');
    console.log('ok forged speakers, unjoined recipients and cross-thread replies are rejected; idempotent retries reach the RPC');
    const edge = fs.readFileSync('supabase/functions/time-league/index.ts', 'utf8');
    assert(edge.indexOf("action.type === 'rival-message'") < edge.indexOf('if (row.version !== body.version)'));
    assert(edge.includes('state: withoutPrivateMessages(next)'));
    assert(edge.includes('p_state: withoutPrivateMessages(state)'));
    assert(edge.includes('projectPublicState(prepared, member.seat_team_id, rivalMessages, data.cards)'));
    assert(edge.includes('!member.joined_at'));
    console.log('PASS: private Vault messaging endpoint boundaries');
})().catch(error => { console.error(error); process.exitCode = 1; });
