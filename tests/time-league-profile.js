'use strict';
const assert = require('assert');
global.window = globalThis;
global.App = {};
App.TimeLeagueRoster = require('../js/shared/time-league-roster.js');
App.TimeLeagueHelmet = require('../js/shared/time-league-helmet.js');
const disk = new Map();
global.localStorage = { getItem: key => disk.get(key) || null, setItem: (key, value) => disk.set(key, value) };
let userId = null;
App.OD = { getCurrentUserId: () => userId };
const Profile = require('../js/shared/time-league-profile.js');
const named = { displayName: 'A Manager', teamName: 'Night Owls', primaryColor: '#123456', secondaryColor: '#fedcba', backdrop: 'aurora', helmet: { ...App.TimeLeagueHelmet.presetHelmet('ice-wolves'), shellColor: '#123456', visor: 'smoke' }, publicProfile: true, lookingForLeague: true };
async function run() {
    assert.equal(Profile.hasSaved(), false);
    assert.equal(Profile.teamDefaults(), null, 'New players keep the existing default setup until they save an identity');
    const invalid = Profile.normalize({ displayName: '\u0000\n  Name  ', teamName: 'x'.repeat(70), primaryColor: 'url(https://example.test)', secondaryColor: '#123', backdrop: '../escape', publicProfile: 'true', lookingForLeague: true, profileId: '<script>' });
    assert.equal(invalid.displayName, 'Name');
    assert.equal(invalid.teamName.length, 40);
    assert(/^#[\da-f]{6}$/i.test(invalid.primaryColor));
    assert(/^#[\da-f]{6}$/i.test(invalid.secondaryColor));
    assert.equal(invalid.backdrop, 'midnight');
    assert.equal(invalid.publicProfile, false);
    assert.equal(invalid.lookingForLeague, false);
    assert.equal(invalid.profileId, undefined);
    let result = await Profile.save(named);
    assert(result.ok);
    assert.equal(result.storage, 'device');
    assert.equal(result.profile.publicProfile, false, 'Guest saves never publish, even if an input says public');
    assert.equal(result.profile.lookingForLeague, false);
    assert.equal(Profile.teamDefaults().name, 'Night Owls');
    assert.equal(Profile.teamDefaults().helmet.visor, 'smoke');
    assert.equal(Profile.teamDefaults().backdrop, 'aurora');
    let calls = 0;
    userId = 'alice';
    App.TimeLeagueRemote = {
        getProfile: async () => ({ ok: true, profile: null }),
        saveProfile: async profile => { calls++; assert.equal(profile.profileId, undefined); return { ok: true, profile: { ...profile, profileId: 'public-alice' } }; },
    };
    assert.equal(Profile.hasSaved(), false, 'A guest design must not pretend to be a saved account profile');
    result = await Profile.get();
    assert.equal(result.profile.teamName, 'Commander');
    assert.equal(calls, 0, 'Reading profiles never writes or publishes them');
    result = await Profile.save({ ...named, profileId: 'forged-id' });
    assert(result.ok);
    assert.equal(result.storage, 'account');
    assert.equal(result.profile.profileId, 'public-alice');
    assert.equal(Profile.readLocal().publicProfile, true);
    result = await Profile.save({ ...Profile.readLocal(), publicProfile: false });
    assert.equal(result.profile.lookingForLeague, false, 'Leaving the public community also leaves discovery');
    userId = 'bob';
    assert.equal(Profile.hasSaved(), false);
    assert.equal(Profile.readLocal().teamName, 'Commander');
    assert.equal(Profile.readLocal().profileId, undefined);
    App.TimeLeagueRemote.getProfile = async () => { userId = 'charlie'; return { ok: true, profile: named }; };
    result = await Profile.get();
    assert.equal(result.ok, false);
    assert.equal(result.profile, undefined, 'An account switch must never return the old account profile');
    assert.equal(Profile.hasSaved('bob'), false);
    App.TimeLeagueRemote.saveProfile = async profile => { userId = 'david'; return { ok: true, profile }; };
    result = await Profile.save(named);
    assert.equal(result.ok, false);
    assert.equal(Profile.hasSaved('charlie'), false);
    userId = 'alice';
    App.TimeLeagueRemote.saveProfile = async () => ({ ok: false, error: 'Network offline' });
    result = await Profile.save({ ...named, teamName: 'Unsaved changes' });
    assert.equal(result.ok, false);
    assert.equal(Profile.readLocal().teamName, 'Night Owls', 'A failed cloud save cannot overwrite the saved identity cache');
    App.TimeLeagueRemote.getProfile = async () => ({ ok: false, error: 'Network offline' });
    result = await Profile.get();
    assert.equal(result.ok, false);
    assert.equal(result.profile.teamName, 'Night Owls', 'Loading errors retain only the same-account cache');
    userId = null;
    assert.equal(Profile.readLocal().publicProfile, false);
    assert.equal(Profile.readLocal().teamName, 'Night Owls', 'Signing out returns the device design, not account data');
    global.localStorage.setItem = () => { throw new Error('Quota exceeded'); };
    result = await Profile.save(named);
    assert.equal(result.ok, false, 'Guest save must surface storage failures');
    console.log('Vault profile: validated identity, guest privacy, explicit publishing, account isolation, race protection, save failures and reusable defaults passed.');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
