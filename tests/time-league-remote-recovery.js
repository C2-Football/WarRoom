'use strict';
const assert = require('node:assert/strict');
global.window = globalThis;
const timers = new Map(), listeners = new Map(), calls = [];
let userId = 'user-a', token = 'session-a', response = async () => ({ data: { ok: true }, error: null });
const db = { functions: { invoke: async (name, input) => { calls.push({ name, ...input }); return response(input.body); } } };
window.App = { OD: { getClient: () => db, getCurrentUserId: () => userId, getSessionToken: () => token } };
window.setInterval = callback => { const id = timers.size + 1; timers.set(id, callback); return id; };
window.clearInterval = id => timers.delete(id);
window.addEventListener = (event, callback) => listeners.set(event, callback);
window.removeEventListener = (event, callback) => { if (listeners.get(event) === callback) listeners.delete(event); };
require('../js/shared/time-league-remote-client.js');
const Remote = App.TimeLeagueRemote;
const flush = () => new Promise(resolve => setImmediate(resolve));
const deferred = () => { let resolve; const promise = new Promise(finish => { resolve = finish; }); return { promise, resolve }; };
(async () => {
    userId = null;
    assert.equal((await Remote.writeOnlineLeague('room', { type: 'week' }, 3)).ok, false);
    assert.equal(calls.length, 0, 'Signed-out users never send a mutation');
    userId = 'user-a';
    const switched = deferred(); response = () => switched.promise;
    const stale = Remote.loadOnlineLeague('room'); userId = 'user-b'; token = 'session-b';
    switched.resolve({ data: { ok: true, row: { id: 'private-a' } }, error: null });
    await assert.rejects(stale, /account changed/);
    assert.equal(calls.at(-1).headers.Authorization, 'Bearer session-a');
    response = async () => ({ error: { context: { json: async () => ({ ok: false, conflict: true }) } } });
    assert.equal((await Remote.writeOnlineLeague('room', { type: 'week' }, 3)).conflict, true, 'Version conflicts cannot become successful saves');
    let writes = 0;
    response = async body => {
        if (body.op === 'action') { writes++; return { data: { ok: true, version: 4 }, error: null }; }
        throw new Error('Connection lost after save');
    };
    const saved = await Remote.writeOnlineLeague('room', { type: 'week' }, 3);
    assert.deepEqual(saved, { ok: true, version: 4, refreshPending: true });
    assert.equal(writes, 1, 'A lost follow-up read must not replay the saved action');
    const pending = deferred(); response = () => pending.promise;
    const received = [], errors = [];
    const stop = Remote.subscribeToLeague('room', row => received.push(row), error => errors.push(error.message));
    const firstPollCount = calls.length;
    timers.values().next().value(); listeners.get('online')(); listeners.get('focus')();
    assert.equal(calls.length, firstPollCount, 'Focus, reconnect and poll triggers share one in-flight read');
    pending.resolve({ data: { ok: false, error: 'Temporarily offline' }, error: null }); await flush();
    assert.equal(errors.length, 1); assert.equal(received.length, 0);
    response = async () => ({ data: { ok: true, row: { id: 'room', version: 4 } }, error: null });
    listeners.get('online')(); await flush();
    assert.deepEqual(received, [{ id: 'room', version: 4 }], 'Returning online recovers the saved snapshot');
    const last = deferred(); response = () => last.promise;
    listeners.get('focus')(); stop(); last.resolve({ data: { ok: true, row: { id: 'room', version: 5 } }, error: null }); await flush();
    assert.equal(received.length, 1, 'An old subscription cannot deliver into a newly opened room');
    assert.equal(timers.size, 0); assert.equal(listeners.size, 0);
    console.log('PASS: authenticated remote reads/writes, account-change isolation, stale-version conflicts, saved-write recovery, nonoverlapping polls, reconnect and unsubscribe cleanup.');
})().catch(error => { console.error(error); process.exitCode = 1; });
